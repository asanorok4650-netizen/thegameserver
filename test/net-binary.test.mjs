import assert from 'node:assert/strict';
import { STATE_BYTES, BATCH_HEADER_BYTES, MAX_BATCH_STATES, encodeState, decodeState, encodeStateBatch, decodeStateBatch, isNewerUint16 } from '../src/net/binary.js';
const bounds = { min: [-100, 0, -50], max: [100, 200, 50] };
const source = { peerId: 17, seq: 65535, state: [12.345, 80.25, -4.2, Math.PI * 1.5, 12.5, 1], pitchRadians: 0.3 };
const bytes = encodeState(source, bounds);
assert.equal(bytes.byteLength, STATE_BYTES);
const decoded = decodeState(bytes, bounds);
assert.equal(decoded.peerId, source.peerId); assert.equal(decoded.seq, source.seq);
assert.ok(Math.abs(decoded.state[0] - source.state[0]) < 0.01);
assert.ok(Math.abs(decoded.state[1] - source.state[1]) < 0.01);
assert.ok(Math.abs(decoded.state[2] - source.state[2]) < 0.01);
assert.ok(Math.abs(decoded.state[3] - source.state[3]) < 0.001);
assert.ok(Math.abs(decoded.state[4] - source.state[4]) < 0.13);
assert.equal(decoded.state[5], 1); assert.ok(Math.abs(decoded.pitch - source.pitchRadians) < 0.02);
assert.equal(decodeState(new Uint8Array(STATE_BYTES - 1), bounds), null);
assert.equal(decodeState(bytes, null), null);
assert.throws(() => encodeState({ ...source, peerId: 0 }, bounds));
assert.throws(() => encodeState({ ...source, seq: 65536 }, bounds));
assert.throws(() => encodeState({ ...source, state: [1000, 0, 0, 0, 0, 0] }, bounds));
assert.throws(() => encodeState({ ...source, state: [0, 0, 0, 0, 40, 0] }, bounds));
assert.equal(isNewerUint16(0, 65535), true); assert.equal(isNewerUint16(65535, 0), false);
assert.equal(isNewerUint16(12, 12), false); assert.equal(isNewerUint16(32768, 0), false);
const records = [source, { peerId: 18, seq: 1, state: [-90, 10, 40, 0, 0, 0] }];
const packet = encodeStateBatch(records, bounds, 123456);
assert.equal(packet.byteLength, BATCH_HEADER_BYTES + records.length * STATE_BYTES);
const batch = decodeStateBatch(packet, bounds);
assert.equal(batch.roomEpoch, 123456); assert.equal(batch.states.length, 2);
assert.equal(batch.states[1].peerId, 18); assert.equal(batch.states[1].state[5], 0);
assert.equal(decodeStateBatch(packet.subarray(0, packet.length - 1), bounds), null);
assert.equal(decodeStateBatch(new Uint8Array(8), bounds), null);
assert.throws(() => encodeStateBatch([], bounds, 1));
assert.throws(() => encodeStateBatch(Array.from({ length: MAX_BATCH_STATES + 1 }, (_, i) => ({ peerId: i + 1, seq: 0, state: [0,0,0,0,0,0] })), bounds, 1));
console.log('net-binary: ok');
